def playbook(style=None):
    """يرجّع قسم خريطة البيع للـ prompt حسب الأسلوب المختار"""
    s = (style or DEFAULT_STYLE).strip().lower()
    if s not in STYLES:
        s = DEFAULT_STYLE
    return _CORE + _STYLE_BLOCKS[s]
