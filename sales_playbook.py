def _norm(style):
    s = (style or DEFAULT_STYLE).strip().lower()
    return s if s in STYLES else DEFAULT_STYLE


# رفض صريح مرتين = نقف (الحازم والمتوازن) — زي قسم «إمتى تقفي»
REFUSALS_TO_STOP = 2


def objection_hint(style, n, refusals=0):
    """تلميح المرحلة لما العميل يعترض أو يرفض — بيتحط في الـ dynamic block.
    n = رقم الاعتراض في المحادثة، refusals = عدد مرات الرفض الصريح («لا»).
    الموديل مابيعدّش لوحده، فإحنا اللي بنقوله هو فين من حد المحاولات بتاع
    أسلوبه — وإلا بيستسلم من أول "غالي" أو أول "لا"."""
    s = _norm(style)
    n = max(int(n or 1), 1)
    refusals = max(int(refusals or 0), 0)
    if s == "calm":
        if refusals:
            return ("🧭 العميل رفض — احترمي قراره فوراً بسطر لطيف، وقوليله إنك موجودة لأي سؤال.")
        return ("🧭 العميل اعترض — اعترفي بقلقه وطمّنيه بمعلومة أو ضمانة حقيقية، "
                "واسيبي له الخطوة الجاية من غير ضغط.")
    if refusals >= REFUSALS_TO_STOP:
        return (f"🧭 العميل رفض صراحةً للمرة رقم {refusals} — وقفي المحاولة: سطر محترم يلخّص "
                "ليه المنتج مناسب له وإنك موجودة لو احتاج، من غير أي طلب تاني.")
    if refusals == 1:
        return ("🧭 العميل لسه قايل «لا» لأول مرة. لو كانت رد على سؤال تاني (مش طلب القرار) "
                "كمّلي عادي. لو كانت رفض للطلب: ده مش نهاية — ⛔ ممنوع توديع أو «احترم قرارك» "
                "أو «لو غيّرت رأيك» في الرد ده. اعترفي بقراره بكلمة، واسأليه سؤال اختيار "
                "واحد يحدد اللي موقّفه (السعر؟ الثقة في المنتج؟ مش محتاجه دلوقتي؟) "
                "+ ضمانة واحدة تشيل المخاطرة (زي الدفع عند الاستلام بعد المعاينة لو ده نظامنا). "
                "لو رفض تاني بعدها، هتقفي.")
    limit = _ATTEMPTS[s]
    h = (f"🧭 العميل في مرحلة اعتراض (الاعتراض رقم {n}، وأسلوبك بيحاول لحد {limit} مرات). "
         "عالجي اللي قاله بالظبط بجملة قصيرة + ضمانة مناسبة، وبعدها ارجعي للإغلاق بسؤال اختيار.")
    if n < limit:
        h += (" ⛔ لسه ماخلصتيش محاولاتك: ممنوع توديع أو \"خد وقتك\" أو \"مش لازم تقرر\" "
              "أو \"لو مش مناسب مفيش مشكلة\" في الرد ده.")
    else:
        h += (" دي آخر محاولة: زاوية جديدة وخطوة صغيرة جداً. لو رفض صراحةً بعدها، "
              "سيبيه باحترام بسطر يلخّص ليه المنتج مناسب له.")
    if n >= 2:
        h += (" ⚠️ راجعي ردودك اللي فاتت: أي ميزة أو مكوّن أو ضمانة ذكرتيها قبل كده "
              "**ممنوع تتكرر** — زاوية جديدة فعلاً، أو سؤال واحد يحدد اللي مقلقه لو مش واضح.")
    return h


