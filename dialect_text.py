# العراقي والمغربي بيستخدموا الفصحى المبسّطة لحد ما نكتبلهم حزمة كاملة
MESSAGES["iraqi"] = MESSAGES["msa"]
MESSAGES["maghreb"] = MESSAGES["msa"]


def get_msg(dialect, key, **kw):
    """
    يرجّع نص بلهجة الـ tenant. بيرجع للمصري لو المفتاح مش موجود
    (عشان أي مفتاح جديد مايكسرش حاجة).
    """
    fam = family(dialect)
    pack = MESSAGES.get(fam) or MESSAGES["egypt"]
    text = pack.get(key) or MESSAGES["egypt"].get(key, "")
    for k, v in kw.items():
        text = text.replace("{" + k + "}", str(v))
    return text
