def family(dialect):
    """يرجّع عيلة اللهجة من النص الحر اللي التاجر كتبه"""
    d = (dialect or "").strip().lower()
    if not d:
        return "egypt"
    for fam, names in _FAMILY_MAP.items():
        for n in names:
            if n in d:
                return fam
    return "egypt"   # الافتراضي


