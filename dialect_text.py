def vocab_hint(dialect):
    """سطرين للـ prompt: استخدمي كذا وتجنّبي كذا"""
    v = VOCAB.get(family(dialect), VOCAB["egypt"])
    return (f"استخدمي مفردات {dialect} الأصيلة ({v['use']}).\n"
            f"وتجنّبي تماماً مفردات {v['avoid']}.")


